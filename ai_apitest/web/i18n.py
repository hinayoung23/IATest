def normalize_locale(value: str | None, *, default: str = DEFAULT_LOCALE) -> str:
    raw = str(value or "").strip().lower().replace("_", "-")
    aliases = {
        "en-us": "en",
        "en-gb": "en",
        "zh-cn": "zh",
        "zh-hans": "zh",
        "ja-jp": "ja",
        "fr-fr": "fr",
        "ru-ru": "ru",
    }
    normalized = aliases.get(raw, raw.split("-", 1)[0])
    return normalized if normalized in SUPPORTED_LOCALES else default


def locale_from_request(query: str = "", cookie_header: str = "") -> str:
    query_locale = (parse_qs(query).get("lang") or [""])[0]
    if query_locale:
        return normalize_locale(query_locale)
    cookie = SimpleCookie()
    try:
        cookie.load(cookie_header or "")
    except Exception:
        return DEFAULT_LOCALE
    item = cookie.get("iatest_lang")
    return normalize_locale(item.value if item else "")


def set_current_locale(locale: str) -> str:
    normalized = normalize_locale(locale)
    _CURRENT_LOCALE.set(normalized)
    return normalized


def current_locale() -> str:
    return _CURRENT_LOCALE.get()


def current_html_lang() -> str:
    return str(SUPPORTED_LOCALES[current_locale()]["html_lang"])


def language_options(locale: str | None = None) -> str:
    active = normalize_locale(locale or current_locale())
    return "".join(
        f'<option value="{code}" {"selected" if code == active else ""}>{escape(str(item["label"]))}</option>'
        for code, item in SUPPORTED_LOCALES.items()
    )


