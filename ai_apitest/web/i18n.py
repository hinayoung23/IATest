def translate_embedded(value: str, locale: str | None = None) -> str:
    active = normalize_locale(locale or current_locale())
    if active == "zh" or not re.search(r"[\u3400-\u9fff]", value):
        return value
    direct = translate_text(value, active)
    if direct != " ".join(value.split()):
        return direct
    catalog = {**_EN, **_LOCAL_OVERRIDES.get(active, {})}
    translated = value
    for source in sorted(catalog, key=len, reverse=True):
        if source in translated:
            translated = translated.replace(source, catalog[source])
    return translated


class _HTMLLocalizer(HTMLParser):
    def __init__(self, locale: str):
        super().__init__(convert_charrefs=False)
        self.locale = locale
        self.output: list[str] = []
        self.stack: list[tuple[str, bool]] = []

    def _skipping(self) -> bool:
        return any(skip for _tag, skip in self.stack)

    def handle_decl(self, decl: str) -> None:
        self.output.append(f"<!{decl}>")

    def handle_starttag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        inherited_skip = self._skipping()
        skip = inherited_skip or tag in _SKIP_ELEMENTS or any(name == "data-i18n-skip" for name, _ in attrs)
        self.stack.append((tag, skip))
        parts = []
        for name, value in attrs:
            if value is None:
                parts.append(name)
                continue
            localized = translate_embedded(value, self.locale) if name in _TRANSLATED_ATTRIBUTES or name == "onsubmit" else value
            parts.append(f'{name}="{escape(localized, quote=True)}"')
        suffix = (" " + " ".join(parts)) if parts else ""
        self.output.append(f"<{tag}{suffix}>")

    def handle_startendtag(self, tag: str, attrs: list[tuple[str, str | None]]) -> None:
        parts = []
        for name, value in attrs:
            if value is None:
                parts.append(name)
            else:
                localized = translate_embedded(value, self.locale) if name in _TRANSLATED_ATTRIBUTES else value
                parts.append(f'{name}="{escape(localized, quote=True)}"')
        suffix = (" " + " ".join(parts)) if parts else ""
        self.output.append(f"<{tag}{suffix}/>")

    def handle_endtag(self, tag: str) -> None:
        self.output.append(f"</{tag}>")
        for index in range(len(self.stack) - 1, -1, -1):
            if self.stack[index][0] == tag:
                del self.stack[index:]
                break

    def handle_data(self, data: str) -> None:
        if self._skipping() or not re.search(r"[\u3400-\u9fff]", data):
            self.output.append(data)
            return
        leading = data[: len(data) - len(data.lstrip())]
        trailing = data[len(data.rstrip()) :]
        self.output.append(leading + translate_text(data.strip(), self.locale) + trailing)

    def handle_entityref(self, name: str) -> None:
        self.output.append(f"&{name};")

    def handle_charref(self, name: str) -> None:
        self.output.append(f"&#{name};")

    def handle_comment(self, data: str) -> None:
        self.output.append(f"<!--{data}-->")

    def handle_pi(self, data: str) -> None:
        self.output.append(f"<?{data}>")


def localize_html(content: str, locale: str | None = None) -> str:
    active = normalize_locale(locale or current_locale())
    if active == "zh":
        return content
    parser = _HTMLLocalizer(active)
    parser.feed(content)
    parser.close()
    return "".join(parser.output)


def localize_task_payload(tasks: list[dict], locale: str | None = None) -> list[dict]:
    active = normalize_locale(locale or current_locale())
    if active == "zh":
        return tasks
    localized = []
    for task in tasks:
        item = dict(task)
        for key in ("label", "detail", "message"):
            if item.get(key):
                item[key] = translate_embedded(str(item[key]), active)
        localized.append(item)
    return localized
